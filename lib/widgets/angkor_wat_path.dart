class AngkorWatSilhouettePainter extends CustomPainter {
  final Color color;
  final bool showStroke;
  final Color? strokeColor;
  final double strokeWidth;

  const AngkorWatSilhouettePainter({
    required this.color,
    this.showStroke = false,
    this.strokeColor,
    this.strokeWidth = 1.0,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final path = _buildAngkorWatPath(size.width, size.height);

    final fillPaint = Paint()
      ..color = color
      ..style = PaintingStyle.fill;
    canvas.drawPath(path, fillPaint);

    if (showStroke) {
      final sPaint = Paint()
        ..color = strokeColor ?? color.withOpacity(0.5)
        ..style = PaintingStyle.stroke
        ..strokeWidth = strokeWidth;
      canvas.drawPath(path, sPaint);
    }
  }

  @override
  bool shouldRepaint(covariant AngkorWatSilhouettePainter oldDelegate) =>
      oldDelegate.color != color ||
      oldDelegate.showStroke != showStroke ||
      oldDelegate.strokeColor != strokeColor ||
      oldDelegate.strokeWidth != strokeWidth;
}

class AngkorWatSilhouetteWidget extends StatelessWidget {
  final double? width;
  final double? height;
  final Color color;
  final bool showStroke;
  final Color? strokeColor;
  final double strokeWidth;

  const AngkorWatSilhouetteWidget({
    super.key,
    this.width,
    this.height,
    this.color = const Color(0x33FFFFFF),
    this.showStroke = false,
    this.strokeColor,
    this.strokeWidth = 1.0,
  });

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      width: width,
      height: height,
      child: CustomPaint(
        painter: AngkorWatSilhouettePainter(
          color: color,
          showStroke: showStroke,
          strokeColor: strokeColor,
          strokeWidth: strokeWidth,
        ),
      ),
    );
  }
}