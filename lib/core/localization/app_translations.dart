class LocalizationService {
  static const String _storageKey = 'language';
  static final RxString currentLanguageCode =
      (GetStorage().read<String>(_storageKey) ?? 'km').obs;

  static Locale get currentLocale {
    if (currentLanguageCode.value == 'en') {
      return const Locale('en', 'US');
    }
    return const Locale('km', 'KH');
  }

  static void changeLanguage(String langCode) {
    final box = GetStorage();
    box.write(_storageKey, langCode);
    currentLanguageCode.value = langCode;
    final locale = langCode == 'en'
        ? const Locale('en', 'US')
        : const Locale('km', 'KH');
    Get.updateLocale(locale);
  }
}
